import {JSDOM,VirtualConsole} from 'jsdom';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const errors=[];const vc=new VirtualConsole();vc.on('error',(...e)=>errors.push(e.join(' ')));vc.on('jsdomError',e=>errors.push(e.message));
const html=await readFile('../Proofloom-review-preview.html','utf8');
const dom=new JSDOM(html,{url:'file:///Proofloom-review-preview.html',runScripts:'outside-only',pretendToBeVisual:true,virtualConsole:vc});
dom.window.scrollTo=()=>{};
let scrolled='';dom.window.HTMLElement.prototype.scrollIntoView=function(){scrolled=this.id;};
const scripts=[...dom.window.document.querySelectorAll('script')].filter(s=>s.type!=='application/ld+json');
for(const s of scripts)dom.window.eval(s.textContent);
await new Promise(r=>setTimeout(r,180));
assert.match(dom.window.document.querySelector('h1').textContent,/Catch packaging/);
const teamLink=[...dom.window.document.querySelectorAll('.nav a')].find(a=>a.textContent==='Team');
assert.ok(teamLink);teamLink.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true,cancelable:true}));
await new Promise(r=>setTimeout(r,100));assert.equal(scrolled,'leadership');
assert.equal(dom.window.document.querySelectorAll('.founder-card').length,2);
assert.deepEqual([...dom.window.document.querySelectorAll('.founder-info h3')].map(e=>e.textContent),['Tolu Akinwale','Michael Ugwu']);
assert.deepEqual([...dom.window.document.querySelectorAll('.founder-role')].map(e=>e.textContent),['Founder & CEO','Co-founder & CTO']);
const footerTeam=[...dom.window.document.querySelectorAll('footer a')].find(a=>a.textContent==='Team');assert.equal(footerTeam.getAttribute('href'),'/#leadership');
const a=dom.window.document.createElement('a');a.href='/brand';dom.window.document.body.append(a);a.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true,cancelable:true}));
await new Promise(r=>setTimeout(r,150));
assert.ok(dom.window.document.querySelector('.brand-stage'));
assert.ok(dom.window.document.querySelector('.brand-stage img').src.startsWith('data:image/svg+xml;base64,'));
assert.equal(dom.window.document.querySelectorAll('.asset-links a').length,15);
assert.deepEqual(errors,[]);dom.window.close();console.log('Offline preview hydration, embedded logo assets Team anchor and brand navigation passed in DOM simulation.');
